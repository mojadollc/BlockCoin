export function MobileNav({ user }: { user: AuthUser }) {
  const pathname = usePathname()
  const tabs = user.role === 'USER' ? USER_TABS : ADMIN_TABS

  return (
    <nav className="md:hidden fixed bottom-0 left-0 right-0 z-50 bg-sidebar border-t border-white/10 safe-bottom">
      <div className="flex items-stretch">
        {tabs.map(tab => {
          const active = tab.href === '/dashboard' || tab.href === '/admin'
            ? pathname === tab.href
            : pathname.startsWith(tab.href)
          return (
            <Link
              key={tab.href}
              href={tab.href}
              className={`flex-1 flex flex-col items-center justify-center py-2 gap-0.5 transition-all active:scale-95 ${
                (tab as any).accent
                  ? active
                    ? 'text-primary'
                    : 'text-primary/70'
                  : active
                    ? 'text-primary'
                    : 'text-surface/40'
              }`}
            >
              {(tab as any).accent ? (
                <div className={`w-11 h-11 rounded-full flex items-center justify-center -mt-5 shadow-lg transition-all ${
                  active ? 'bg-primary' : 'bg-primary/90'
                }`}>
                  <span className="text-bg">{tab.icon}</span>
                </div>
              ) : (
                tab.icon
              )}
              <span className={`text-[10px] font-medium ${(tab as any).accent ? 'mt-1' : ''}`}>
                {tab.label}
              </span>
            </Link>
          )
        })}
      </div>
    </nav>
  )
}
